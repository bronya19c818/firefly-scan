"""Rebuild the checked-in Android vectors from pinned, unmodified Tabler SVGs.

Run with --download only when deliberately importing/updating official sources.
The normal offline run verifies hashes and rejects unsupported SVG features.
"""
import argparse
import hashlib
import json
from pathlib import Path
from urllib.request import urlopen
import xml.etree.ElementTree as ET
from xml.sax.saxutils import quoteattr

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "third_party/tabler-icons"
ANDROID = "http://schemas.android.com/apk/res/android"


def convert(source: bytes) -> str:
    svg = ET.fromstring(source)
    assert svg.tag == "{http://www.w3.org/2000/svg}svg", svg.tag
    assert set(svg.attrib) <= {"width", "height", "viewBox", "fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin", "class"}, svg.attrib
    assert svg.attrib["width"] == svg.attrib["height"] == "24"
    assert svg.attrib["viewBox"] == "0 0 24 24"
    assert svg.attrib["fill"] == "none" and svg.attrib["stroke"] == "currentColor"
    assert svg.attrib["stroke-width"] == "2"
    assert svg.attrib["stroke-linecap"] == svg.attrib["stroke-linejoin"] == "round"
    paths = []
    for child in svg:
        assert child.tag == "{http://www.w3.org/2000/svg}path", child.tag
        assert set(child.attrib) <= {"d", "stroke", "fill"}, child.attrib
        if child.attrib.get("stroke") == "none" and child.attrib.get("fill") == "none":
            continue  # SVG's invisible 24x24 bounds path must stay transparent.
        assert set(child.attrib) == {"d"}, child.attrib
        paths.append('    <path android:fillColor="#00000000" android:strokeColor="#FF000000"\n'
                     '        android:strokeWidth="2" android:strokeLineCap="round" android:strokeLineJoin="round"\n'
                     f'        android:pathData={quoteattr(child.attrib["d"])} />')
    assert paths
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Tabler Icons v3.49.0 / MIT; generated by tools/import_tabler_icons.py. -->\n'
            f'<vector xmlns:android="{ANDROID}" android:width="24dp" android:height="24dp"\n'
            '    android:viewportWidth="24" android:viewportHeight="24">\n'
            + '\n'.join(paths) + '\n</vector>\n')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--download", action="store_true")
    args = parser.parse_args()
    manifest_path = SOURCE / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    base = f'https://raw.githubusercontent.com/tabler/tabler-icons/{manifest["commit"]}'
    (SOURCE / "icons").mkdir(parents=True, exist_ok=True)
    output = ROOT / "app/src/main/res/drawable"
    for icon in manifest["icons"]:
        path = SOURCE / "icons" / (icon["tabler"] + ".svg")
        if args.download:
            with urlopen(base + "/icons/outline/" + path.name, timeout=30) as response:
                data = response.read()
            digest = hashlib.sha256(data).hexdigest()
            if icon.get("sha256"):
                assert digest == icon["sha256"], path.name
            path.write_bytes(data)
            icon["sha256"] = digest
        data = path.read_bytes()
        assert hashlib.sha256(data).hexdigest() == icon["sha256"], path.name
        (output / ("ic_tabler_" + icon["tabler"].replace("-", "_") + ".xml")).write_text(convert(data), encoding="utf-8")
    if args.download:
        license_path = SOURCE / "LICENSE"
        with urlopen(base + "/LICENSE", timeout=30) as response:
            license_data = response.read()
        license_hash = hashlib.sha256(license_data).hexdigest()
        if manifest.get("license_sha256"):
            assert manifest["license_sha256"] == license_hash
        license_path.write_bytes(license_data)
        manifest["license_sha256"] = license_hash
        manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    assert hashlib.sha256((SOURCE / "LICENSE").read_bytes()).hexdigest() == manifest["license_sha256"]
    packaged_license = ROOT / "app/src/main/assets/licenses/tabler-icons.txt"
    packaged_license.parent.mkdir(parents=True, exist_ok=True)
    packaged_license.write_bytes((SOURCE / "LICENSE").read_bytes())
    print(f'Verified and generated {len(manifest["icons"])} vectors ({manifest["version"]}).')


if __name__ == "__main__":
    main()
